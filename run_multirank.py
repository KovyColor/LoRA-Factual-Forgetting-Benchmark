# 2. MODEL INITIALIZATION (Загружается ровно 1 раз)
# ------------------------------------------------------------------------------
model_id = "unsloth/llama-3-8b-Instruct"
print(f"[*] Initializing Base Model: {model_id}...")

tokenizer = AutoTokenizer.from_pretrained(model_id, use_fast=True, clean_up_tokenization_spaces=False)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token
tokenizer.padding_side = "right"

bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.float16,
    bnb_4bit_use_double_quant=True
)

base_model = AutoModelForCausalLM.from_pretrained(
    model_id,
    quantization_config=bnb_config,
    device_map="auto",
    dtype=torch.float16
)
base_model = prepare_model_for_kbit_training(base_model, use_gradient_checkpointing=True)

