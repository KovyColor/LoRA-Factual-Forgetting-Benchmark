# 3. COLLATOR & EVALUATION HARNESS
# ------------------------------------------------------------------------------
@dataclass
class FactualDataCollator:
    tokenizer: AutoTokenizer
    max_length: int = 128

    def __call__(self, instances: Sequence[Dict]) -> Dict[str, torch.Tensor]:
        input_ids_batch, labels_batch, attention_mask_batch = [], [], []
        for inst in instances:
            p_tokens = self.tokenizer.encode(inst["prompt"], add_special_tokens=True)
            t_tokens = self.tokenizer.encode(inst["target"], add_special_tokens=False) + [self.tokenizer.eos_token_id]
            inp = p_tokens + t_tokens
            lbl = [-100] * len(p_tokens) + t_tokens
            mask = [1] * len(inp)

            if len(inp) > self.max_length:
                inp, lbl, mask = inp[:self.max_length], lbl[:self.max_length], mask[:self.max_length]

            input_ids_batch.append(torch.tensor(inp, dtype=torch.long))
            labels_batch.append(torch.tensor(lbl, dtype=torch.long))
            attention_mask_batch.append(torch.tensor(mask, dtype=torch.long))

        return {
            "input_ids": torch.nn.utils.rnn.pad_sequence(input_ids_batch, batch_first=True, padding_value=self.tokenizer.pad_token_id),
            "labels": torch.nn.utils.rnn.pad_sequence(labels_batch, batch_first=True, padding_value=-100),
            "attention_mask": torch.nn.utils.rnn.pad_sequence(attention_mask_batch, batch_first=True, padding_value=0)
        }

def evaluate_exact_match(model, tokenizer, dataset):
    model.eval()
    correct = 0
    total = len(dataset)
    with torch.no_grad():
        for item in dataset:
            inputs = tokenizer(item["prompt"], return_tensors="pt").to("cuda")
            outputs = model.generate(
                **inputs,
                max_new_tokens=15,
                do_sample=False,
                pad_token_id=tokenizer.pad_token_id
            )
            gen = tokenizer.decode(outputs[0][inputs["input_ids"].shape[1]:], skip_special_tokens=True).strip()
            if gen.lower().startswith(item["target"].strip().lower()):
                correct += 1
    return (correct / total) * 100.0

