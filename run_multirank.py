# 4. MULTI-RANK PIPELINE (БЕЗ ПЕРЕЗАГРУЗКИ МОДЕЛИ)
# ------------------------------------------------------------------------------
train_dataset, test_factual, test_mmlu = load_sample_datasets()
collator = FactualDataCollator(tokenizer=tokenizer)

# Замер общего Baseline до любых адаптеров
print("\n" + "=" * 70)
print("PRE-TUNING GLOBAL BASELINE")
print("=" * 70)
base_factual_acc = evaluate_exact_match(base_model, tokenizer, test_factual)
base_mmlu_acc = evaluate_exact_match(base_model, tokenizer, test_mmlu)
print(f"[>] Baseline Factual Recall: {base_factual_acc:.2f}%")
print(f"[>] Baseline MMLU Benchmark: {base_mmlu_acc:.2f}%")

ranks_to_test = [8, 16, 64]

for r in ranks_to_test:
    print("\n" + "=" * 70)
    print(f"RUNNING EXPERIMENT FOR LoRA RANK: r={r}")
    print("=" * 70)

    lora_config = LoraConfig(
        r=r,
        lora_alpha=r * 2,
        target_modules=["q_proj", "v_proj"],
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM"
    )

    peft_model = get_peft_model(base_model, lora_config)
    peft_model.print_trainable_parameters()
    peft_model.config.use_cache = False

    args = TrainingArguments(
        output_dir=f"./lora_r{r}_out",
        per_device_train_batch_size=2,
        gradient_accumulation_steps=2,
        learning_rate=2e-4,
        max_steps=20,
        logging_steps=10,
        fp16=True,
        optim="paged_adamw_32bit",
        report_to="none",
        save_strategy="no",
        remove_unused_columns=False
    )

    trainer = Trainer(
        model=peft_model,
        train_dataset=train_dataset,
        args=args,
        data_collator=collator
    )

    trainer.train()

    post_fact = evaluate_exact_match(peft_model, tokenizer, test_factual)
    post_mmlu = evaluate_exact_match(peft_model, tokenizer, test_mmlu)
    f_delta = base_mmlu_acc - post_mmlu
    toi = (2 * post_fact * (100 - f_delta)) / (post_fact + (100 - f_delta) + 1e-8)

    print("-" * 50)
    print(f"RESULTS FOR r={r}:")
    print(f"  * Post-tuning Recall (Acc_new): {post_fact:.2f}%")
    print(f"  * Post-tuning MMLU Score:      {post_mmlu:.2f}%")
    print(f"  * Forgetting Delta (F):         {f_delta:.2f} p.p.")
    print(f"  * Trade-Off Index (TOI):       {toi:.2f}")
    print("-" * 50)

    # Снимаем адаптер перед следующим циклом и чистим VRAM
    peft_model.unload()
    gc.collect()
    torch.cuda.empty_cache()

print("\n[V] ALL MULTI-RANK RUNS COMPLETED SUCCESSFULLY!")

